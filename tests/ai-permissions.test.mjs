import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const admin = '11111111-1111-4111-8111-111111111111', other = '22222222-2222-4222-8222-222222222222';
await db.exec(`create role anon; create role authenticated;
  alter default privileges grant execute on functions to anon, authenticated;
  create schema auth; create table auth.users(id uuid primary key);
  create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
  insert into auth.users values ('${admin}'), ('${other}');
  create table public.photo_admins(user_id uuid primary key references auth.users);
  insert into public.photo_admins values ('${admin}');
  create function public.is_photo_admin() returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.photo_admins where user_id=auth.uid())$$;
`);
const setup = await readFile(new URL('../supabase/ai-setup.sql', import.meta.url), 'utf8');
await db.exec(setup); await db.exec(setup);
const login = async (role, id = '') => {
  await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec(`set role ${role}`);
};
const reserve = async () => (await db.query('select public.reserve_photo_ai_request() as allowed')).rows[0].allowed;
await login('anon'); await assert.rejects(reserve(), /permission denied/);
await login('authenticated', other); await assert.rejects(reserve(), /Admin access required/);
await login('authenticated', admin);
await assert.rejects(db.query('select * from public.photo_ai_usage'), /permission denied/);
await assert.rejects(db.query('delete from public.photo_ai_usage'), /permission denied/);
for (let i = 0; i < 30; i++) assert.equal(await reserve(), true);
assert.equal(await reserve(), false, 'The hourly cap must hold');
await db.exec('reset role');
await db.exec("update public.photo_ai_usage set hour_started=now()-interval '2 hours', day_count=99");
await login('authenticated', admin);
assert.equal(await reserve(), true); assert.equal(await reserve(), false, 'The daily cap survives an hourly reset');
await db.exec('reset role'); await db.exec("update public.photo_ai_usage set day_started=now()-interval '25 hours',hour_started=now()-interval '2 hours'");
await login('authenticated', admin); assert.equal(await reserve(), true, 'Allowance returns after the windows expire');
await db.exec('reset role'); await db.exec(setup); await login('authenticated', admin);
assert.equal(await reserve(), true, 'Rerunning setup preserves usage');
await db.exec('reset role');
assert.equal((await db.query('select day_count from public.photo_ai_usage')).rows[0].day_count, 2);
await db.close();
console.log('AI allowance permissions, hourly/daily limits, reset windows, and repeatable setup passed.');
